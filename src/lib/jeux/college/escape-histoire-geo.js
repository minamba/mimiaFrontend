/**
 * Les six étapes de la classe, dans l'ordre du récit : chacune tire l'une de
 * ses variantes et mélange ses choix. Les phrases suivent la variante :
 * « 5e-etape-1 » pour la première, « 5e-etape-1-b » pour la deuxième…
 */
export function serie(graine = Date.now(), niveau = 'SIXIEME') {
  const { au, melanger } = outils(graine);
  const classe = ETAPES[niveau] ? niveau : 'SIXIEME';
  const prefixe = PREFIXE[classe];
  const pieces = ETAPES[classe].map((e) => e.piece);

  return ETAPES[classe].map((etape, i) => {
    const e = au(etape.variantes);
    const consigne = `${prefixe}-etape-${i + 1}${e.suffixe ? `-${e.suffixe}` : ''}`;
    const libelles = melanger([e.bonne, ...Object.keys(e.pieges)]);
    return {
      consigne,
      question: e.question,
      choix: libelles.map((l) => ({ cle: l, libelle: l })),
      bonne: e.bonne,
      pieges: { ...e.pieges },
      aide: `${consigne}-aide`,
      recit: e.recit,
      cadenas: { avant: pieces.slice(0, i), piece: etape.piece, total: MANCHES },
      competence: e.competence,
    };
  });
}

export function verdict(m, cle) {
  if (cle === m.bonne) return 'juste';
  return m.pieges?.[cle] ?? `${m.consigne}-regle`;
}

